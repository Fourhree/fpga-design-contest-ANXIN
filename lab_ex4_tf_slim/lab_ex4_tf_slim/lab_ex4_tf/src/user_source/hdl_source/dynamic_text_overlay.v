// Combinational overlays share the registered video timing; no RGB latency.
module dynamic_text_overlay #(
    parameter integer PIXEL_HZ = 25000000
) (
    input  wire        clk,
    input  wire        rst_n,
    input  wire        vsync,
    input  wire        de,
    input  wire [9:0]  pixel_x,
    input  wire [23:0] rgb_in,
    input  wire [2:0]  active_index,
    input  wire        auto_enabled,
    output wire [23:0] rgb_out
);
    reg [11:0] line_y;
    reg de_q;
    reg vs_q;
    wire frame_start = vs_q && !vsync;

    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            line_y <= 12'd0;
            de_q <= 1'b0;
            vs_q <= 1'b1;
        end else begin
            de_q <= de;
            vs_q <= vsync;
            if (!vsync)
                line_y <= 12'd0;
            else if (de_q && !de)
                line_y <= line_y + 1'b1;
        end
    end

    wire [23:0] emergency_rgb;
    wire [23:0] mode_rgb;

    // The old PIC/MANUAL/AUTO scrolling subtitle is removed. This instance
    // is the only subtitle and is enabled exclusively for image 6.
    emergency_subtitle_overlay u_subtitle (
        .clk(clk), .rst_n(rst_n), .frame_start(frame_start),
        .enable(active_index == 3'd5),
        .de(de), .pixel_x(pixel_x), .pixel_y(line_y), .rgb_in(rgb_in),
        .rgb_out(emergency_rgb), .overlay_active()
    );

    playback_mode_overlay u_mode (
        .enable(1'b1), .auto_enabled(auto_enabled),
        .de(de), .pixel_x(pixel_x), .pixel_y(line_y), .rgb_in(emergency_rgb),
        .rgb_out(mode_rgb), .overlay_active()
    );

    timestamp_osd #(.PIXEL_HZ(PIXEL_HZ)) u_timer (
        .pix_clk(clk), .pix_rst_n(rst_n), .sys_rst_n(rst_n),
        .enable(1'b1), .vsync(vsync), .de(de),
        .pixel_x(pixel_x), .pixel_y(line_y), .rgb_in(mode_rgb),
        .rgb_out(rgb_out), .ts_active()
    );
endmodule


module playback_mode_overlay (
    input  wire        enable,
    input  wire        auto_enabled,
    input  wire        de,
    input  wire [9:0]  pixel_x,
    input  wire [11:0] pixel_y,
    input  wire [23:0] rgb_in,
    output wire [23:0] rgb_out,
    output wire        overlay_active
);
    // 16x16 Song font glyphs: SHOU, DONG, ZI.
    localparam [255:0] GLYPH_SHOU = 256'h3f00010001003ff8010001000100fffe01000100010001000500020000000000;
    localparam [255:0] GLYPH_DONG = 256'h7c40004001fc0044fe4420442044208448844484fd0445040228041000000000;
    localparam [255:0] GLYPH_ZI   = 256'h04001ff01010101010101ff0101010101ff01010101010101ff0101000000000;

    function [15:0] mode_glyph_row;
        input [1:0] glyph_id;
        input [3:0] row;
        begin
            case (glyph_id)
                2'd0: mode_glyph_row = GLYPH_SHOU[255-row*16 -: 16];
                2'd1: mode_glyph_row = GLYPH_DONG[255-row*16 -: 16];
                default: mode_glyph_row = GLYPH_ZI[255-row*16 -: 16];
            endcase
        end
    endfunction

    wire in_region = enable && de && pixel_x >= 10'd8 && pixel_x < 10'd40 &&
                     pixel_y >= 12'd8 && pixel_y < 12'd24;
    wire glyph_sel = pixel_x >= 10'd24;
    wire [3:0] glyph_x = pixel_x - (glyph_sel ? 10'd24 : 10'd8);
    wire [3:0] glyph_y = pixel_y - 12'd8;
    wire [1:0] mode_glyph_id = glyph_sel ? 2'd1 :
                               (auto_enabled ? 2'd2 : 2'd0);
    wire [15:0] selected_row = mode_glyph_row(mode_glyph_id, glyph_y);
    wire mode_hit = in_region && selected_row[15-glyph_x];

    assign overlay_active = mode_hit;
    assign rgb_out = mode_hit ? 24'h000000 : rgb_in;
endmodule


